/**
 * File → New → Project → Spring Boot: the project is generated by a Spring Initializr server (start.spring.io by default,
 * changeable in the wizard), unpacked into the new project directory and imported with Gradle or Maven.
 * The wizard UI, download and import come from the platform's web starter support; this class only speaks the
 * Initializr protocol.
 */
internal class SpringInitializrModuleBuilder : WebStarterModuleBuilder() {
  override fun getBuilderId(): String = "phantom.spring.initializr"
  override fun getWeight(): Int = JVM_WEIGHT + 100
  override fun getNodeIcon(): Icon = ICON
  override fun getPresentableName(): String = PhantomSpringBootBundle.message("initializr.name")
  override fun getDescription(): String = PhantomSpringBootBundle.message("initializr.description")
  override fun getDefaultServerUrl(): String = "https://start.spring.io"

  // Shown until the server's own lists arrive, then replaced by them
  override fun getLanguages(): List<StarterLanguage> = InitializrMetadata.KNOWN_LANGUAGES
  override fun getProjectTypes(): List<StarterProjectType> = listOf(
    StarterProjectType("gradle-project", "Gradle - Groovy"),
    StarterProjectType("gradle-project-kotlin", "Gradle - Kotlin"),
    StarterProjectType("maven-project", "Maven"),
  )
  override fun getLanguageLevels(): List<StarterLanguageLevel> = listOf("25", "21", "17").map { InitializrMetadata.javaLevel(it) }
  override fun getDefaultLanguageLevel(): StarterLanguageLevel = InitializrMetadata.javaLevel("17")
  override fun getPackagingTypes(): List<StarterAppPackaging> = listOf(StarterAppPackaging("jar", "Jar"), StarterAppPackaging("war", "War"))
  override fun getConfigurationFileFormats(): List<StarterConfigFileFormat> =
    listOf(StarterConfigFileFormat("properties", "Properties"), StarterConfigFileFormat("yaml", "YAML"))
  override fun getDefaultVersion(): String = "0.0.1-SNAPSHOT"
  override fun isPackageNameEditable(): Boolean = true

  override fun getCustomizedMessages(): CustomizedMessages = CustomizedMessages().apply {
    frameworkVersionLabel = PhantomSpringBootBundle.message("initializr.boot.version")
    serverUrlDialogTitle = PhantomSpringBootBundle.message("initializr.server.url")
  }

  override fun loadServerOptions(serverUrl: String): WebStarterServerOptions =
    InitializrMetadata.parse(loadJsonData(serverUrl, InitializrMetadata.ACCEPT))

  override fun isVersionAvailable(frameworkVersion: WebStarterFrameworkVersion): Boolean =
    BootVersion.parse(frameworkVersion.id) != null

  override fun getDependencyState(frameworkVersion: WebStarterFrameworkVersion, dependency: WebStarterDependency): DependencyState =
    dependencyState(frameworkVersion.id, dependency)

  override fun composeGeneratorUrl(serverUrl: String, starterContext: WebStarterContext): Url =
    Urls.newFromEncoded(serverUrl.trimEnd('/') + "/starter.zip").addParameters(generatorParameters(starterContext))

  override fun extractGeneratorResult(tempZipFile: File, contentEntryDir: File) {
    // The archive holds one folder named after baseDir; its contents go straight into the project directory
    unzipSubfolder(tempZipFile, contentEntryDir)
  }

  companion object {
    private val ICON = IconLoader.getIcon("/icons/phantom/springBoot.svg", SpringInitializrModuleBuilder::class.java.classLoader)

    /** Whether [dependency] can be picked with Spring Boot [bootVersion], from its version range in the metadata. */
    internal fun dependencyState(bootVersion: String, dependency: WebStarterDependency): DependencyState {
      val range = (dependency as? InitializrDependency)?.versionRange ?: return DependencyAvailable
      val version = BootVersion.parse(bootVersion) ?: return DependencyAvailable
      if (version in range) return DependencyAvailable
      return DependencyUnavailable(PhantomSpringBootBundle.message("initializr.dependency.unavailable", range.describe()))
    }

    /** The query of `/starter.zip`, named as the Initializr API names them. */
    internal fun generatorParameters(context: WebStarterContext): Map<String, String> = buildMap {
      context.projectType?.let { put("type", it.id) }
      put("language", context.language.id)
      context.frameworkVersion?.let { put("bootVersion", it.id) }
      put("baseDir", context.artifact)
      put("groupId", context.group)
      put("artifactId", context.artifact)
      put("name", context.artifact)
      put("version", context.version)
      put("packageName", context.packageName)
      context.packaging?.let { put("packaging", it.id) }
      context.languageLevel?.let { put("javaVersion", it.id) }
      context.configFileFormat?.let { put("configurationFileFormat", it.id) }
      if (context.dependencies.isNotEmpty()) put("dependencies", context.dependencies.map { it.id }.sorted().joinToString(","))
    }
  }
}
