package dev.phantom.querydsl

import com.intellij.psi.JavaPsiFacade
import com.intellij.psi.PsiClass
import com.intellij.psi.PsiClassType
import com.intellij.psi.PsiElement
import com.intellij.psi.PsiField
import com.intellij.psi.PsiModifier
import com.intellij.psi.search.GlobalSearchScope
import com.intellij.psi.search.searches.ClassInheritorsSearch
import com.intellij.psi.util.CachedValueProvider
import com.intellij.psi.util.CachedValuesManager
import com.intellij.psi.util.PsiModificationTracker

/**
 * QueryDSL's generated query types: `QOrder extends EntityPathBase<Order>` (or BeanPath, for an embeddable) in the
 * entity's package, with a field per property and `public static final QOrder order`.
 */
object QClasses {
  private const val QUERYDSL = "com.querydsl."
  private val TRANSIENT = setOf(
    "jakarta.persistence.Transient", "javax.persistence.Transient", "org.springframework.data.annotation.Transient",
    "com.querydsl.core.annotations.QueryTransient",
  )

  /** A class generated by QueryDSL: named Q… and extending one of QueryDSL's paths. */
  fun isQClass(psi: PsiClass): Boolean =
    psi.name?.startsWith("Q") == true && generateSequence(psi.superClass) { it.superClass }.any { it.qualifiedName?.startsWith(QUERYDSL) == true }

  /** The entity (or embeddable, superclass) a Q class is for: the type argument of its path, else the class it is named after. */
  fun entityOf(q: PsiClass): PsiClass? = CachedValuesManager.getCachedValue(q) {
    val fromType = (q.extendsListTypes.firstOrNull()?.parameters?.firstOrNull() as? PsiClassType)?.resolve()
    val entity = fromType ?: q.qualifiedName?.let { name ->
      val simple = q.name!!.removePrefix("Q")
      JavaPsiFacade.getInstance(q.project).findClass(name.removeSuffix(q.name!!) + simple, GlobalSearchScope.allScope(q.project))
    }
    CachedValueProvider.Result.create(entity?.takeUnless { it == q }, PsiModificationTracker.MODIFICATION_COUNT)
  }

  /** The Q class QueryDSL generated for [entity], when there is one. */
  fun qClassOf(entity: PsiClass): PsiClass? = CachedValuesManager.getCachedValue(entity) {
    val name = entity.qualifiedName
    val q = if (name == null || entity.containingClass != null) null else {
      val qName = name.removeSuffix(entity.name!!) + "Q" + entity.name
      JavaPsiFacade.getInstance(entity.project).findClass(qName, GlobalSearchScope.allScope(entity.project))
        ?.takeIf { isQClass(it) && entityOf(it) == entity }
    }
    CachedValueProvider.Result.create(q, PsiModificationTracker.MODIFICATION_COUNT)
  }

  /** What a field of a Q class stands for: the entity property, or the entity for the static instance (`QOrder.order`). */
  fun targetOf(field: PsiField): PsiElement? {
    val q = field.containingClass ?: return null
    if (!isQClass(q)) return null
    val entity = entityOf(q) ?: return null
    if (field.hasModifierProperty(PsiModifier.STATIC)) {
      return entity.takeIf { (field.type as? PsiClassType)?.resolve() == q }
    }
    val name = field.name
    return entity.findFieldByName(name, true)
      ?: entity.findMethodsByName("get" + name.replaceFirstChar(Char::uppercase), true).firstOrNull()
      ?: entity.findMethodsByName("is" + name.replaceFirstChar(Char::uppercase), true).firstOrNull()
  }

  /** The Q class fields for an entity field: in its class's Q class and those of its subclasses (a mapped superclass). */
  fun qFieldsOf(field: PsiField): List<PsiField> {
    if (field.hasModifierProperty(PsiModifier.STATIC)) return emptyList()
    val owner = field.containingClass ?: return emptyList()
    if (isQClass(owner)) return emptyList()
    val classes = listOf(owner) + ClassInheritorsSearch.search(owner, GlobalSearchScope.projectScope(owner.project), true).findAll()
    return classes.mapNotNull { qClassOf(it)?.findFieldByName(field.name, false) }.filter { !it.hasModifierProperty(PsiModifier.STATIC) }
  }

  /** The static instances of a Q class (`QOrder.order`). */
  fun instancesOf(q: PsiClass): List<PsiField> =
    q.fields.filter { it.hasModifierProperty(PsiModifier.STATIC) && (it.type as? PsiClassType)?.resolve() == q }

  /** The fields QueryDSL makes a path for: not static, not transient. */
  fun isProperty(field: PsiField): Boolean =
    !field.hasModifierProperty(PsiModifier.STATIC) && !field.hasModifierProperty(PsiModifier.TRANSIENT) &&
      field.annotations.none { it.qualifiedName in TRANSIENT }

  /** The property fields of a Q class (not its static instances, `_super` or other helpers starting with `_`). */
  fun qProperties(q: PsiClass): List<PsiField> =
    q.fields.filter { !it.hasModifierProperty(PsiModifier.STATIC) && !it.name.startsWith("_") }
}
