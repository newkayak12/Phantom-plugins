"""
Writes mermaid.js.LICENSE.txt next to the bundled mermaid.js (the file the bundle's first line points to): every npm
package whose code mermaid.js.map shows in the bundle, with its version, license and license file.

    python3 updateLicenses.py

Needs npm. The packages are installed into a temporary directory with the versions updateMermaidJs.sh builds with
(mermaid from gradle.properties, the rest from browser/*/build.gradle.kts), with --ignore-scripts; their license files
are read from there. Run it again after updateMermaidJs.sh.
"""
import json
import os
import re
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
resources = os.path.join(here, "..", "src", "main", "resources", "com", "phantom", "mermaid", "markdown", "jcef")
mermaid_version = re.search(r"^mermaidVersion\s*=\s*(\S+)", open(os.path.join(here, "gradle.properties")).read(), re.M).group(1)
# npm(...) dependencies of browser/mermaid-api and browser/extension, and the webpack loaders whose runtime code the
# Kotlin/JS build puts into the bundle for the CSS
roots = [f"mermaid@{mermaid_version}", "@mermaid-js/mermaid-zenuml@0.2.0", "@fortawesome/fontawesome-free@6.4.0", "style-loader", "css-loader"]

sources = json.load(open(os.path.join(resources, "mermaid.js.map")))["sources"]
# "webpack://extension/../../node_modules/cytoscape-fcose/node_modules/cose-base/cose-base.js" -> "cytoscape-fcose/node_modules/cose-base"
paths = sorted({m.group(1) for s in sources for m in [re.search(r"node_modules/((?:(?:@[^/]+/)?[^/]+/node_modules/)*(?:@[^/]+/)?[^/]+)", s)] if m})

license_file = re.compile(r"^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$", re.I)

with tempfile.TemporaryDirectory() as work:
    subprocess.run(["npm", "install", "--prefix", work, "--ignore-scripts", "--no-audit", "--no-fund", "--silent", *roots], check=True)
    modules = os.path.join(work, "node_modules")
    entries = {}
    for path in paths:
        directory = os.path.join(modules, path)
        if not os.path.isdir(directory):  # npm laid the tree out differently: the hoisted copy
            directory = os.path.join(modules, path.split("node_modules/")[-1])
        package = json.load(open(os.path.join(directory, "package.json")))
        name, version = package["name"], package["version"]
        if (name, version) in entries:
            continue
        license_name = package.get("license") or (package.get("licenses") or [{}])[0].get("type") or "see the license file"
        repository = package.get("repository")
        url = package.get("homepage") or (repository.get("url") if isinstance(repository, dict) else repository) or f"https://www.npmjs.com/package/{name}"
        texts = [(f, open(os.path.join(directory, f), encoding="utf-8", errors="replace").read().strip())
                 for f in sorted(os.listdir(directory)) if license_file.match(f)]
        entries[(name, version)] = (license_name, url, texts)

out = os.path.join(resources, "mermaid.js.LICENSE.txt")
with open(out, "w", encoding="utf-8") as f:
    f.write(f"Third-party code in mermaid.js (mermaid {mermaid_version} with the Mermaid plugin's browser code)\n")
    f.write("=" * 78 + "\n\n")
    f.write("mermaid.js is a webpack bundle of the npm packages below and of Kotlin/JS code (the Kotlin standard library\n"
            "and the plugin's own, Apache License 2.0). Each package keeps its license; the text follows its entry.\n"
            "Generated by browser-build/updateLicenses.py from mermaid.js.map; the versions are those npm resolves for the\n"
            f"dependency ranges of mermaid {mermaid_version} when the file is generated.\n")
    for (name, version), (license_name, url, texts) in sorted(entries.items()):
        f.write("\n" + "-" * 78 + "\n")
        f.write(f"{name} {version}\nLicense: {license_name}\nProject: {url}\n")
        if name == "@fortawesome/fontawesome-free":
            f.write("Font Awesome Free: icons under CC BY 4.0, fonts under SIL OFL 1.1, code under MIT (https://fontawesome.com/license/free)\n")
        if not texts:
            f.write("(the package has no license file)\n")
        for file_name, text in texts:
            f.write(f"\n--- {name}/{file_name} ---\n{text}\n")
print(f"{out}: {len(entries)} packages", file=sys.stderr)
