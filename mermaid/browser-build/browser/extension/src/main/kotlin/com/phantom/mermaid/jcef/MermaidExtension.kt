package com.phantom.mermaid.jcef

import com.phantom.mermaid.api.MermaidRenderResult
import com.phantom.mermaid.api.appendTo
import com.phantom.mermaid.jcef.impl.decode
import kotlinx.browser.window
import kotlinx.coroutines.flow.collect
import kotlinx.coroutines.flow.conflate
import org.w3c.dom.Element
import org.w3c.dom.HTMLElement
import org.w3c.dom.asList
import kotlin.time.ExperimentalTime
import kotlin.time.measureTime

private fun collectBlocks(): List<HTMLElement> {
  val nodes = window.document.querySelectorAll("div.mermaid").asList()
  // Just for sanity reason
  return nodes.filterIsInstance<HTMLElement>()
}

@OptIn(ExperimentalTime::class)
private suspend fun performRender() {
  val time = measureTime {
    val blocks = collectBlocks()
    console.log("${blocks.size} blocks will be generated by mermaid")
    renderBlocks(blocks)
  }
  console.log("Generated all mermaid blocks in $time")
}

suspend fun renderBlocks(blocks: List<HTMLElement>) {
  for (block in blocks) {
    // renderAsync for some reason depends on some global state,
    // so it is not possible to run it in parallel
    processBlock(block)
  }
}

/**
 * Phantom: rendered diagrams by cache id (content and theme), not by element. Incremental DOM recreates and empties the
 * blocks on every patch, so a cache keyed by element missed (every diagram was drawn again on each keystroke) and kept
 * every replaced element and its SVG alive. The oldest entries go first once [MAX_CACHED] is reached.
 */
private const val MAX_CACHED = 64
private val renderedByCacheId = LinkedHashMap<String, MermaidRenderResult>()
private const val RENDERED_ATTRIBUTE = "data-phantom-rendered"

suspend fun processBlock(block: HTMLElement) {
  block.removeAttribute("data-processed")
  val cacheId = block.getAttribute("data-cache-id")
  checkNotNull(cacheId) { "data-cache-id was not set for block" }
  val content = block.getAttribute("data-actual-fence-content")
  checkNotNull(content) { "data-actual-fence-content was not set for block" }

  // the patch kept this block and its diagram: nothing to do
  if (block.getAttribute(RENDERED_ATTRIBUTE) == cacheId && block.firstElementChild != null) return

  val cached = renderedByCacheId.remove(cacheId)
  if (cached != null) {
    renderedByCacheId[cacheId] = cached
    cached.appendTo(block)
  }
  else {
    val generated = renderBlock(block, cacheId, decode(content)) ?: return
    renderedByCacheId[cacheId] = generated
    while (renderedByCacheId.size > MAX_CACHED) {
      renderedByCacheId.remove(renderedByCacheId.keys.first())
    }
  }
  block.setAttribute(RENDERED_ATTRIBUTE, cacheId)
}

suspend fun markdownExtensionMain() {
  performRender()
  // Phantom: one pass at a time (mermaid cannot render two diagrams at once), and patches that arrive during a pass
  // are merged into a single next pass instead of each queuing its own
  IncrementalDom.afterPatchEvents().conflate().collect { performRender() }
}
